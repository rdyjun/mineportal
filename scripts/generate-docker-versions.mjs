import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const DOC = "docs/docker-versions.md";
const SKIP_DIRECTORIES = new Set([".git", ".gradle", "build", "dist", "node_modules"]);

// Postgres publishes the patch as the second component (`18.7`). Temurin puts the
// build after an underscore (`17.0.21_9`). A single component (`18-alpine`) floats.
const EXACT_VERSION = /(?:^|[^0-9])\d+\.\d+(?:\.\d+)*(?:_\d+)?(?=$|[^0-9])/;
const IMAGE_REFERENCE =
  /^(?:(?<registry>[a-zA-Z0-9](?:[a-zA-Z0-9.-]*[a-zA-Z0-9])?(?::\d+)?)\/)?(?<name>[a-zA-Z0-9][a-zA-Z0-9._-]*(?:\/[a-zA-Z0-9][a-zA-Z0-9._-]*)*)(?::(?<tag>[A-Za-z0-9_][A-Za-z0-9._-]{0,127}))?(?:@(?<digest>sha256:[a-fA-F0-9]{64}))?$/;

export function parseImageReference(reference) {
  const match = IMAGE_REFERENCE.exec(reference);
  if (!match) return null;
  return {
    registry: match.groups.registry || null,
    name: match.groups.name,
    tag: match.groups.tag || null,
    digest: match.groups.digest || null,
  };
}

export function isExactPin(reference) {
  const parsed = parseImageReference(reference);
  if (!parsed) return false;
  if (parsed.digest) return true;
  if (!parsed.tag) return false;
  return EXACT_VERSION.test(parsed.tag);
}

export async function collectImages(root) {
  const files = (await walk(root)).sort((left, right) => left.localeCompare(right));
  const stages = [];
  const serviceImages = [];
  const builds = [];

  for (const file of files) {
    const text = await readFile(path.join(root, file), "utf8");
    const kind = fileKind(file);
    if (kind === "dockerfile") stages.push(...parseDockerfile(file, text));
    if (kind === "compose") {
      const parsed = parseCompose(file, text);
      serviceImages.push(...parsed.images);
      builds.push(...parsed.builds);
    }
    if (kind === "workflow") serviceImages.push(...parseWorkflow(file, text));
  }

  const servicesByDockerfile = new Map();
  for (const build of builds) {
    const dockerfile = resolveDockerfile(build);
    const services = servicesByDockerfile.get(dockerfile) || [];
    services.push(build.service);
    servicesByDockerfile.set(dockerfile, services);
  }

  const rows = [];
  for (const stage of stages) {
    const services = [...new Set(servicesByDockerfile.get(stage.file) || [])].sort();
    if (services.length === 0) {
      rows.push({ ...stage, service: "—" });
      continue;
    }
    for (const service of services) rows.push({ ...stage, service });
  }
  rows.push(...serviceImages);
  rows.sort(
    (left, right) =>
      left.file.localeCompare(right.file) ||
      left.line - right.line ||
      left.service.localeCompare(right.service),
  );
  return rows;
}

export function renderDocument(rows) {
  const lines = [
    "<!-- Generated by scripts/generate-docker-versions.mjs. Do not edit by hand. -->",
    "",
    "# Docker image versions",
    "",
    "Generated from Dockerfiles, Compose files, and container image references in",
    "GitHub Actions workflows. Do not edit this file by hand.",
    "",
    "Regenerate it from the repository root:",
    "",
    "```bash",
    "node scripts/generate-docker-versions.mjs",
    "```",
    "",
    "Check without writing:",
    "",
    "```bash",
    "node scripts/generate-docker-versions.mjs --check",
    "```",
    "",
    "A reference is pinned when its tag contains a numeric version with at least two",
    "components (`18.7`, `17.0.21`, `17.0.21_9`) or when it includes a `sha256` digest.",
    "Major-only tags (`18-alpine`) and `latest` are not pins.",
    "",
    "`.github/workflows/docker-versions.yml` regenerates this file on pull requests that",
    "change a Dockerfile, a Compose file, a workflow, this document, or the generator.",
    "On a branch in this repository, including a Dependabot branch, it commits and pushes",
    "the updated file. A push made with `GITHUB_TOKEN` does not start other workflows; if",
    "the pull request needs status checks on that new commit, approve the waiting runs or",
    "re-run them. If the push is rejected, the check fails and prints the command to run.",
    "",
    "| Service | Role | Image | Defined in |",
    "| --- | --- | --- | --- |",
  ];
  if (rows.length === 0) lines.push("| — | — | — | — |");
  for (const row of rows) {
    lines.push(
      `| ${cell(row.service)} | ${cell(row.role)} | \`${cell(row.image)}\` | \`${cell(row.file)}:${row.line}\` |`,
    );
  }
  lines.push("");
  return lines.join("\n");
}

async function main() {
  const options = parseArgs(process.argv.slice(2));
  const rows = await collectImages(options.root);
  const next = renderDocument(rows);
  const target = path.join(options.root, DOC);
  const previous = await readFile(target, "utf8").catch((error) => {
    if (error.code === "ENOENT") return null;
    throw error;
  });
  const changed = previous !== next;
  const unpinned = rows.filter((row) => !isExactPin(row.image));

  if (!options.check && changed) {
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, next);
  }

  for (const row of unpinned) {
    console.error(`Not an exact pin: ${row.file}:${row.line} ${row.image}`);
  }
  if (rows.length === 0) {
    console.error("No container images found in Dockerfiles, Compose files, or workflows.");
  }
  if (options.check && changed) {
    console.error(
      "docs/docker-versions.md is out of date. Run: node scripts/generate-docker-versions.mjs",
    );
  }
  if (unpinned.length > 0 || rows.length === 0) process.exit(2);
  if (options.check && changed) process.exit(3);
}

function parseArgs(args) {
  let root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  let check = false;
  for (let index = 0; index < args.length; index += 1) {
    const arg = args[index];
    if (arg === "--check") {
      check = true;
    } else if (arg === "--root") {
      const value = args[index + 1];
      if (!value) {
        console.error("--root requires a directory");
        process.exit(1);
      }
      root = path.resolve(value);
      index += 1;
    } else {
      console.error(`Unknown argument: ${arg}`);
      process.exit(1);
    }
  }
  return { root, check };
}

function fileKind(file) {
  const base = path.posix.basename(file);
  if (base === "Dockerfile" || base.startsWith("Dockerfile.") || base.endsWith(".Dockerfile")) {
    return "dockerfile";
  }
  if (/^(?:docker-)?compose(?:\..+)?\.ya?ml$/.test(base)) return "compose";
  if (file.startsWith(".github/workflows/") && (file.endsWith(".yml") || file.endsWith(".yaml"))) {
    return "workflow";
  }
  return null;
}

function parseDockerfile(file, text) {
  const aliases = new Set();
  const stages = [];
  for (const [index, line] of text.split("\n").entries()) {
    const from = parseFrom(line.trim());
    if (!from) continue;
    if (from.stage) aliases.add(from.stage);
    if (from.image === "scratch" || aliases.has(from.image)) continue;
    stages.push({ line: index + 1, image: from.image, alias: from.stage });
  }
  return stages.map((stage, index) => ({
    file,
    line: stage.line,
    image: stage.image,
    role: stage.alias || (index === stages.length - 1 ? "runtime" : "stage"),
  }));
}

function parseFrom(trimmed) {
  if (!trimmed || trimmed.startsWith("#") || !/^FROM\b/i.test(trimmed)) return null;
  let rest = stripInlineComment(trimmed.replace(/^FROM\s+/i, ""));
  while (rest.startsWith("--")) {
    const flag = /^--[\w-]+(?:=\S+|\s+\S+)\s+/.exec(rest);
    if (!flag) return null;
    rest = rest.slice(flag[0].length);
  }
  const named = /^(\S+)\s+[Aa][Ss]\s+(\S+)$/.exec(rest);
  if (named) return { image: named[1], stage: named[2] };
  if (!rest || /\s/.test(rest)) return null;
  return { image: rest, stage: null };
}

function parseCompose(file, text) {
  const images = [];
  const builds = [];
  let inServices = false;
  let servicesIndent = -1;
  let service = null;
  let serviceIndent = -1;
  let build = null;
  let buildIndent = -1;

  function flushBuild() {
    if (service && build) {
      builds.push({
        file,
        service,
        context: build.context,
        dockerfile: build.dockerfile,
      });
    }
    build = null;
    buildIndent = -1;
  }

  for (const [index, line] of text.split("\n").entries()) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const indent = leadingSpaces(line, file, index + 1);
    if (!inServices) {
      if (indent === 0 && trimmed === "services:") {
        inServices = true;
        servicesIndent = indent;
      }
      continue;
    }
    if (indent <= servicesIndent) {
      flushBuild();
      inServices = false;
      service = null;
      continue;
    }
    if (indent === servicesIndent + 2 && /^[\w.-]+:$/.test(trimmed)) {
      flushBuild();
      service = trimmed.slice(0, -1);
      serviceIndent = indent;
      continue;
    }
    if (!service || indent <= serviceIndent) continue;
    if (build && indent <= buildIndent) flushBuild();
    if (trimmed === "build:" || trimmed.startsWith("build:")) {
      flushBuild();
      const inline = stripInlineComment(trimmed.slice("build:".length).trim());
      if (inline) {
        builds.push({ file, service, context: unquote(inline), dockerfile: null });
      } else {
        build = { context: null, dockerfile: null };
        buildIndent = indent;
      }
      continue;
    }
    if (build && indent > buildIndent) {
      if (trimmed.startsWith("context:")) {
        build.context = unquote(stripInlineComment(trimmed.slice("context:".length).trim()));
      } else if (trimmed.startsWith("dockerfile:")) {
        build.dockerfile = unquote(stripInlineComment(trimmed.slice("dockerfile:".length).trim()));
      }
      continue;
    }
    if (trimmed.startsWith("image:")) {
      const image = unquote(stripInlineComment(trimmed.slice("image:".length).trim()));
      if (image) images.push({ file, line: index + 1, image, service, role: "service" });
    }
  }
  flushBuild();
  return { images, builds };
}

function parseWorkflow(file, text) {
  const service = path.posix.basename(file).replace(/\.ya?ml$/, "");
  const images = [];
  for (const [index, line] of text.split("\n").entries()) {
    const trimmed = stripInlineComment(line.trim());
    if (!trimmed || trimmed.startsWith("#")) continue;
    let image = null;
    if (trimmed.startsWith("image:")) {
      image = unquote(trimmed.slice("image:".length).trim());
    } else {
      const parsed = parseImageReference(trimmed);
      if (parsed?.tag || parsed?.digest) image = trimmed;
    }
    if (image) images.push({ file, line: index + 1, image, service, role: "workflow" });
  }
  return images;
}

function resolveDockerfile(build) {
  const composeDir = path.posix.dirname(build.file);
  const context = build.context || ".";
  const dockerfile = build.dockerfile || "Dockerfile";
  const base = path.posix.normalize(path.posix.join(composeDir, context));
  let resolved = path.posix.normalize(path.posix.join(base, dockerfile));
  if (resolved.startsWith("./")) resolved = resolved.slice(2);
  return resolved;
}

function stripInlineComment(value) {
  let quote = null;
  for (let index = 0; index < value.length; index += 1) {
    const character = value[index];
    if (quote) {
      if (character === quote) quote = null;
      continue;
    }
    if (character === '"' || character === "'") {
      quote = character;
      continue;
    }
    if (character === "#" && (index === 0 || /\s/.test(value[index - 1]))) {
      return value.slice(0, index).trim();
    }
  }
  return value.trim();
}

function unquote(value) {
  if (
    (value.startsWith('"') && value.endsWith('"') && value.length >= 2) ||
    (value.startsWith("'") && value.endsWith("'") && value.length >= 2)
  ) {
    return value.slice(1, -1);
  }
  return value;
}

function leadingSpaces(line, file, lineNumber) {
  const indent = /^[ \t]*/.exec(line)[0];
  if (indent.includes("\t")) {
    throw new Error(`${file}:${lineNumber}: Compose image parsing does not support tabs`);
  }
  return indent.length;
}

function cell(value) {
  return String(value).replaceAll("|", "\\|").replaceAll("\n", " ");
}

async function walk(root, directory = root, files = []) {
  const entries = await readdir(directory, { withFileTypes: true });
  for (const entry of entries) {
    if (SKIP_DIRECTORIES.has(entry.name)) continue;
    const full = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      await walk(root, full, files);
    } else if (entry.isFile()) {
      files.push(path.relative(root, full).split(path.sep).join("/"));
    }
  }
  return files;
}

const invokedDirectly =
  process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href;

if (invokedDirectly) {
  main().catch((error) => {
    console.error(error);
    process.exit(1);
  });
}
